"""The built-in name tables: who a Bluetooth company number, service UUID or
address block belongs to. Nothing here asks anyone anything: no lookup leaves
the house.

The files in data/ are generated by tools/build_device_tables.py from the
Bluetooth SIG and IEEE lists (numbers and names only, see
THIRD_PARTY_NOTICES.md). They are read once, off the event loop, the first time
a snapshot is built (async_load_tables). Until then, and if a file can't be
read, every lookup answers None.
"""

from __future__ import annotations

import logging
import struct
import sys
import threading
from array import array
from bisect import bisect_left
from pathlib import Path
from typing import Any, Optional

_LOGGER = logging.getLogger(__name__)

_DATA = Path(__file__).parent / "data"
_MAC_MAGIC = b"PSMAC1"
_MAC_BITS = (36, 28, 24)  # longest block first: a smaller block sits inside a bigger one

_lock = threading.Lock()
_loaded = False
_companies: dict[int, str] = {}
_members: dict[str, str] = {}
_mac: Optional["_MacTable"] = None


class _MacTable:
    """The address blocks, as arrays and one block of name bytes, so a list of
    54,000 blocks costs well under a megabyte in memory and a name is decoded
    only when it is asked for."""

    def __init__(self, raw: bytes) -> None:
        if raw[:len(_MAC_MAGIC)] != _MAC_MAGIC:
            raise ValueError("not a maker table")
        pos = len(_MAC_MAGIC)
        blob_len, n24, n28, n36 = struct.unpack_from("<IIII", raw, pos)
        pos += 16
        self._names = raw[pos:pos + blob_len]
        pos += blob_len
        self._starts = array("I", [0])
        at = self._names.find(b"\n")
        while at >= 0:
            self._starts.append(at + 1)
            at = self._names.find(b"\n", at + 1)
        self._blocks: dict[int, tuple[array, array]] = {}
        for bits, count in ((24, n24), (28, n28), (36, n36)):
            code = "Q" if bits > 32 else "I"
            prefixes = array(code, bytes(array(code).itemsize * count))
            value = 0
            for i in range(count):
                shift = delta = 0
                while True:
                    b = raw[pos]
                    pos += 1
                    delta |= (b & 0x7F) << shift
                    if b < 0x80:
                        break
                    shift += 7
                value += delta
                prefixes[i] = value
            ids = array("H")
            ids.frombytes(raw[pos:pos + 2 * count])
            if sys.byteorder == "big":
                ids.byteswap()
            pos += 2 * count
            self._blocks[bits] = (prefixes, ids)

    def _name(self, i: int) -> str:
        start = self._starts[i]
        end = self._starts[i + 1] - 1 if i + 1 < len(self._starts) else len(self._names)
        return self._names[start:end].decode("utf-8")

    def lookup(self, addr48: int) -> Optional[str]:
        for bits in _MAC_BITS:
            prefixes, ids = self._blocks[bits]
            key = addr48 >> (48 - bits)
            i = bisect_left(prefixes, key)
            if i < len(prefixes) and prefixes[i] == key:
                return self._name(ids[i])
        return None

    def __len__(self) -> int:
        return sum(len(p) for p, _ in self._blocks.values())


def _read_tsv(fname: str) -> list[tuple[str, str]]:
    rows = []
    for line in (_DATA / fname).read_text(encoding="utf-8").splitlines():
        key, sep, name = line.partition("\t")
        if sep and name:
            rows.append((key, name))
    return rows


def load_tables() -> None:
    """Read the tables, once. Blocking: async_load_tables runs it off the loop."""
    global _loaded, _companies, _members, _mac
    if _loaded:
        return
    with _lock:
        if _loaded:
            return
        try:
            _companies = {int(k, 16): v for k, v in _read_tsv("bt_companies.tsv")}
            _members = {k.lower(): v for k, v in _read_tsv("bt_members.tsv")}
        except (OSError, ValueError) as err:
            _LOGGER.warning("PadSpan's Bluetooth name tables could not be read: %s", err)
        try:
            _mac = _MacTable((_DATA / "mac_makers.bin").read_bytes())
        except (OSError, ValueError, struct.error, IndexError) as err:
            _LOGGER.warning("PadSpan's address maker table could not be read: %s", err)
        _loaded = True


async def async_load_tables(hass: Any) -> None:
    """Load the tables off the event loop. Costs nothing after the first time."""
    if not _loaded:
        await hass.async_add_executor_job(load_tables)


def company(company_id: int) -> Optional[str]:
    """Who Bluetooth SIG gave this company number to."""
    return _companies.get(company_id)


def service_owner(uuid16: str) -> Optional[str]:
    """Which company holds this 16-bit service UUID (four lower-case hex digits)."""
    return _members.get(uuid16)


def address_maker(address: Any) -> Optional[str]:
    """Who IEEE assigned the block this address is in, from its first 3 to 4.5 bytes.

    Only means something for an address that really is maker-assigned; the
    caller decides that (ble_enrichment.apply_address_maker).
    """
    if _mac is None:
        return None
    digits = "".join(c for c in str(address or "") if c != ":")
    if len(digits) != 12:
        return None
    try:
        return _mac.lookup(int(digits, 16))
    except ValueError:
        return None


def table_sizes() -> dict[str, int]:
    """How many entries each table holds (0 until loaded)."""
    return {"companies": len(_companies), "members": len(_members), "mac_blocks": len(_mac) if _mac else 0}
